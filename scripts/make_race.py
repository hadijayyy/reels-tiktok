"""Build the month-by-month balances for the "Gaji Sama" race video.

    python scripts/make_race.py

Writes src/scenes/gajiSamaData.ts (balances per month and the frame timeline) and
public/audio/gajisama-events.json (times of coin clinks and the finish, for make_music.py "race").
All four earn Rp8 juta a month. Amounts are in juta rupiah. Illustration only, not advice.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30
TARGET = 100.0
INTRO = 3.2        # seconds before month 0 starts counting
SEC_PER_MONTH = 0.58

# Investor: Rp2 juta a month into an index fund. A rough first year (the market dips), then an
# steady 1.15% a month. Over the whole race that averages about 6.6% a year. Penabung: Rp2 juta a month into a savings box, no interest.
def investor_return(m: int) -> float:
    if m <= 6:
        return -0.025
    if m <= 10:
        return 0.004
    return 0.0115


def series(months: int):
    pen, inv, bor, jud = [0.0], [0.0], [0.0], [0.0]
    for m in range(1, months + 1):
        pen.append(pen[-1] + 2.0)
        inv.append(inv[-1] * (1 + investor_return(m)) + 2.0)
        # Boros saves Rp1 juta, but every few months a sale, a gadget or paylater eats it
        b = bor[-1] + 1.0
        if m % 4 == 0:
            b = max(0.4, b - 4.5)
        bor.append(round(b, 2))
        # Judol: early wins, then losses, then online loans
        j = {1: 2.0, 2: 6.5, 3: 15.0, 4: 24.0, 5: 11.0, 6: 3.0, 7: 0.0}.get(m)
        if j is None:
            j = jud[-1] - (2.5 if m < 30 else 1.0)
        jud.append(max(j, -45.0))
    return pen, inv, bor, jud


def main() -> None:
    months = 60
    pen, inv, bor, jud = series(months)
    win = next(m for m, v in enumerate(inv) if v >= TARGET)
    pen, inv, bor, jud = (s[: win + 1] for s in (pen, inv, bor, jud))
    inv[win] = TARGET  # the counter stops at the target
    start = round(INTRO * FPS)
    month_frames = round(SEC_PER_MONTH * FPS)
    finish = start + win * month_frames
    frames = finish + 5 * FPS + 25
    data = {
        "WIN_MONTH": win,
        "START": start,
        "MONTH_FRAMES": month_frames,
        "FINISH": finish,
        "FRAMES": frames,
        "PENABUNG": [round(v, 2) for v in pen],
        "INVESTOR": [round(v, 2) for v in inv],
        "BOROS": [round(v, 2) for v in bor],
        "JUDOL": [round(v, 2) for v in jud],
    }
    out = os.path.join(ROOT, "src", "scenes", "gajiSamaData.ts")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/make_race.py. Do not edit by hand. Amounts in juta rupiah.\n")
        for k, v in data.items():
            f.write(f"export const {k} = {json.dumps(v)};\n")
    events = {
        "seconds": frames / FPS,
        "clinks": [(start + m * month_frames) / FPS for m in range(1, win + 1)],
        "finish": finish / FPS,
    }
    with open(os.path.join(ROOT, "public", "audio", "gajisama-events.json"), "w") as f:
        json.dump(events, f)
    print(f"investor hits {TARGET} in month {win}; penabung {pen[-1]}, boros {bor[-1]}, judol {jud[-1]}; {frames} frames ({frames / FPS:.1f}s)")
    print("investor:", [round(v, 1) for v in inv[::4]])


if __name__ == "__main__":
    main()
